// Encode the existing, unmodified Apache-2.0 Roboto face for browser/Worker use.
// No fetch, Node filesystem access, or bundler asset loader is needed at runtime.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

var source = new URL("../../native-core/fonts/Roboto.ttf", import.meta.url);
var target = new URL("../fonts/Roboto-Regular.js", import.meta.url);
var bytes = await readFile(source);
var hash = createHash("sha256").update(bytes).digest("hex");
var chunks = bytes.toString("base64").match(/.{1,76}/g);
await writeFile(
  target,
  `// Roboto Regular — Copyright 2012 Google Inc. All Rights Reserved.
// Apache-2.0; see LICENSE.txt and ../THIRD_PARTY_NOTICES.md.
// Generated by scripts/generate-default-font.mjs; do not edit.
// Unmodified TTF SHA-256: ${hash}
var base64 = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join("");

/** Decode the bundled face only when Recipe first needs its default font. */
export function defaultFontBytes() {
  return Uint8Array.from(atob(base64), (character) => character.charCodeAt(0));
}
`,
);
