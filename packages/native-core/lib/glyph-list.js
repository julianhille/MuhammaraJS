/**
 * Parse the glyph list into a lookup from glyph name to Unicode text. Values
 * are normalized to NFC, so a name such as `Omega` decodes to U+03A9 rather
 * than the canonically equivalent U+2126 and matches text typed by users.
 *
 * @returns {Object<string, string>} Unicode text by glyph name.
 */
function parseGlyphList() {
  var glyphs = Object.create(null);
  var entries = GLYPH_LIST.trim().split(/\s+/);
  for (var index = 0; index < entries.length; index++) {
    var separator = entries[index].indexOf(":");
    var codes = entries[index].slice(separator + 1).split(",");
    var text = "";
    for (var code = 0; code < codes.length; code++) {
      text += String.fromCodePoint(parseInt(codes[code], 16));
    }
    glyphs[entries[index].slice(0, separator)] = text.normalize("NFC");
  }
  return glyphs;
}

var GLYPHS = null;

/**
 * Get the glyph-name lookup, parsing the list on first use so that loading the
 * package stays cheap.
 *
 * @returns {Object<string, string>} Unicode text by glyph name.
 */
function glyphs() {
  if (!GLYPHS) GLYPHS = parseGlyphList();
  return GLYPHS;
}

module.exports = { glyphs: glyphs };
